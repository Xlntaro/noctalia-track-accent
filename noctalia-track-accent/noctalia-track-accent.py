#!/usr/bin/env python3
"""Event-driven MPRIS cover-art accent writer for Umbriel's audio-theme.

The helper writes a small generated shader that preserves the existing audio
brightness formula. The Noctalia service starts/stops it; no metadata is ever
sent through a shell command line.
"""

from __future__ import annotations

import argparse
import colorsys
from concurrent.futures import Future, ThreadPoolExecutor
from dataclasses import asdict, dataclass
import fcntl
import hashlib
import json
import math
import os
from pathlib import Path
import re
import select
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from typing import Optional
from urllib.parse import unquote, urlparse
from urllib.request import Request, urlopen

Rgb = tuple[int, int, int]

MARKER = "// Generated by Noctalia Track Accent; do not edit this generated shader."
MAX_DOWNLOAD = 8 * 1024 * 1024
PALETTE_MODES = frozenset(("single", "gradient"))
IDLE_MODES = frozenset(("native", "last_cover", "palette", "fixed", "hidden"))
NOCTALIA_MPRIS_BUS = "dev.noctalia.Mpris"
NOCTALIA_MPRIS_PATH = "/dev/noctalia/Mpris"
NOCTALIA_MPRIS_INTERFACE = "dev.noctalia.Mpris"
HISTOGRAM = re.compile(
    r"^\s*(\d+):\s*\(\s*([\d.]+),\s*([\d.]+),\s*([\d.]+),\s*([\d.]+)\)"
)
HEX_COLOR = re.compile(r"^#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?$")


@dataclass(frozen=True)
class ShaderSettings:
    palette_mode: str = "gradient"
    idle_mode: str = "native"
    silence_brightness: float = 0.4
    dark_color_floor: float = 0.5
    spectrum_gain: float = 1.8
    bass_gain: float = 0.35
    max_colors: int = 4
    gradient_speed: float = 0.0
    fallback_color: str = "#7C6FDC"


def expand(path: str) -> Path:
    return Path(os.path.expanduser(path)).resolve()


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent,
                                     prefix=f".{path.name}.", delete=False) as output:
        output.write(content)
        output.flush()
        os.fsync(output.fileno())
        temporary = Path(output.name)
    os.replace(temporary, path)


def glsl_color(rgb: Rgb) -> str:
    normalized = ", ".join(f"{component / 255.0:.6f}" for component in rgb)
    return f"vec4({normalized}, 1.0)"


def glsl_number(value: float) -> str:
    rendered = f"{value:.6f}".rstrip("0").rstrip(".")
    return rendered if "." in rendered else rendered + ".0"


def glsl_hex_color(value: str) -> str:
    if not HEX_COLOR.fullmatch(value):
        value = ShaderSettings.fallback_color
    red, green, blue = (int(value[index:index + 2], 16) for index in (1, 3, 5))
    alpha = int(value[7:9], 16) if len(value) == 9 else 255
    normalized = ", ".join(
        f"{component / 255.0:.6f}" for component in (red, green, blue, alpha)
    )
    return f"vec4({normalized})"


def fallback_glsl(settings: ShaderSettings) -> str:
    if settings.idle_mode == "palette":
        return """vec4 color = noctalia_track_accent_available
    ? noctalia_track_accent_at(gradient_position)
    : umbriel_palette_at(fract(gradient_position));"""
    if settings.idle_mode == "fixed":
        return f"""vec4 color = noctalia_track_accent_available
    ? noctalia_track_accent_at(gradient_position)
    : {glsl_hex_color(settings.fallback_color)};"""
    fallback = "vec4(0.0)" if settings.idle_mode == "hidden" else "umbriel_sample(uv)"
    return f"""if (!noctalia_track_accent_available) return {fallback};
  vec4 color = noctalia_track_accent_at(gradient_position);"""


def shader_source(
    colors: tuple[Rgb, ...], settings: ShaderSettings = ShaderSettings()
) -> str:
    enabled = "true" if colors else "false"
    accent_colors = colors or ((0, 0, 0),)
    declarations = "\n".join(
        f"const vec4 noctalia_track_accent_{index} = {glsl_color(color)};"
        for index, color in enumerate(accent_colors)
    )
    # Keep four declarations available for the branch-only GLSL selector below.
    # This avoids relying on dynamic uniform-array indexing in Umbriel shaders.
    declarations += "\n" + "\n".join(
        f"const vec4 noctalia_track_accent_{index} = {glsl_color(accent_colors[-1])};"
        for index in range(len(accent_colors), 4)
    )
    return f'''{MARKER}
// Source artwork affects the border tint; the spectrum still drives brightness.
const bool noctalia_track_accent_available = {enabled};
const int noctalia_track_accent_count = {len(colors)};
{declarations}

vec4 noctalia_track_accent_at(float position) {{
  if (noctalia_track_accent_count == 1) return noctalia_track_accent_0;

  float phase = fract(position) * float(noctalia_track_accent_count);
  float blend = smoothstep(0.0, 1.0, fract(phase));
  if (noctalia_track_accent_count == 2) {{
    return phase < 1.0
      ? mix(noctalia_track_accent_0, noctalia_track_accent_1, blend)
      : mix(noctalia_track_accent_1, noctalia_track_accent_0, blend);
  }}
  if (noctalia_track_accent_count == 3) {{
    if (phase < 1.0) return mix(noctalia_track_accent_0, noctalia_track_accent_1, blend);
    if (phase < 2.0) return mix(noctalia_track_accent_1, noctalia_track_accent_2, blend);
    return mix(noctalia_track_accent_2, noctalia_track_accent_0, blend);
  }}
  if (phase < 1.0) return mix(noctalia_track_accent_0, noctalia_track_accent_1, blend);
  if (phase < 2.0) return mix(noctalia_track_accent_1, noctalia_track_accent_2, blend);
  if (phase < 3.0) return mix(noctalia_track_accent_2, noctalia_track_accent_3, blend);
  return mix(noctalia_track_accent_3, noctalia_track_accent_0, blend);
}}

vec4 border(vec2 uv) {{
  vec2 center = uv - vec2(0.5);
  float position = atan(center.y, center.x) / 6.2831853 + 0.5;
  float gradient_position = {"position" if settings.gradient_speed == 0.0 else f"position + umbriel_time * {glsl_number(settings.gradient_speed)}"};
  float band = abs(position * 2.0 - 1.0);
  float signal = umbriel_audio_spectrum(band);
  float bass = umbriel_audio_spectrum(0.0);

  {fallback_glsl(settings)}

  // Keep silence visible even when the artwork accent is almost black. Scaling
  // by the strongest channel retains the tint and saturation of dark colors.
  float color_peak = max(max(color.r, color.g), color.b);
  vec3 visible_color = color_peak > 0.001
    ? color.rgb * max(1.0, {glsl_number(settings.dark_color_floor)} / color_peak)
    : vec3({glsl_number(settings.dark_color_floor)});
  float brightness = clamp({glsl_number(settings.silence_brightness)} + signal * {glsl_number(settings.spectrum_gain)} + bass * {glsl_number(settings.bass_gain)}, 0.0, 1.0);
  // Umbriel requires premultiplied RGBA from border shaders.
  return vec4(visible_color * color.a * brightness, color.a);
}}
'''


def metadata_path(state_dir: Path) -> Path:
    return state_dir / "managed-shader.json"


def backup_path(state_dir: Path) -> Path:
    return state_dir / "audio-theme.shader.before-track-accent.glsl"


def read_metadata(state_dir: Path) -> dict:
    try:
        return json.loads(metadata_path(state_dir).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def prepare_shader(state_dir: Path, shader: Path) -> bool:
    """Preserve the user's shader once, before the first managed write."""
    if not shader.exists():
        return False
    current = shader.read_text(encoding="utf-8")
    if current.startswith(MARKER):
        return True
    backup = backup_path(state_dir)
    if not backup.exists():
        atomic_write(backup, current)
        atomic_write(metadata_path(state_dir), json.dumps({"shader": str(shader)}, indent=2) + "\n")
    return True


def write_colors(
    state_dir: Path,
    shader: Path,
    colors: tuple[Rgb, ...],
    settings: ShaderSettings,
) -> None:
    if not prepare_shader(state_dir, shader):
        return
    content = shader_source(colors, settings)
    try:
        old = shader.read_text(encoding="utf-8")
    except OSError:
        old = ""
    if old != content:
        atomic_write(shader, content)


def palette_mode_path(state_dir: Path) -> Path:
    return state_dir / "palette-mode"


def settings_path(state_dir: Path) -> Path:
    return state_dir / "shader-settings.json"


def last_colors_path(state_dir: Path) -> Path:
    return state_dir / "last-colors.json"


def last_accent_colors_path(state_dir: Path) -> Path:
    return state_dir / "last-accent-colors.json"


def bounded_number(value: object, default: float, minimum: float, maximum: float) -> float:
    try:
        number = float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return default
    return min(maximum, max(minimum, number)) if math.isfinite(number) else default


def settings_from_mapping(values: dict) -> ShaderSettings:
    defaults = ShaderSettings()
    palette_mode = values.get("palette_mode", defaults.palette_mode)
    idle_mode = values.get("idle_mode", defaults.idle_mode)
    fallback_color = values.get("fallback_color", defaults.fallback_color)
    try:
        max_colors = int(values.get("max_colors", defaults.max_colors))
    except (TypeError, ValueError):
        max_colors = defaults.max_colors
    return ShaderSettings(
        palette_mode=palette_mode if palette_mode in PALETTE_MODES else defaults.palette_mode,
        idle_mode=idle_mode if idle_mode in IDLE_MODES else defaults.idle_mode,
        silence_brightness=bounded_number(
            values.get("silence_brightness"), defaults.silence_brightness, 0.0, 1.0
        ),
        dark_color_floor=bounded_number(
            values.get("dark_color_floor"), defaults.dark_color_floor, 0.0, 1.0
        ),
        spectrum_gain=bounded_number(
            values.get("spectrum_gain"), defaults.spectrum_gain, 0.0, 3.0
        ),
        bass_gain=bounded_number(values.get("bass_gain"), defaults.bass_gain, 0.0, 1.5),
        max_colors=min(4, max(1, max_colors)),
        gradient_speed=bounded_number(
            values.get("gradient_speed"), defaults.gradient_speed, -0.5, 0.5
        ),
        fallback_color=(
            fallback_color
            if isinstance(fallback_color, str) and HEX_COLOR.fullmatch(fallback_color)
            else defaults.fallback_color
        ),
    )


def read_settings(state_dir: Path) -> ShaderSettings:
    try:
        values = json.loads(settings_path(state_dir).read_text(encoding="utf-8"))
        if isinstance(values, dict):
            return settings_from_mapping(values)
    except (OSError, ValueError):
        pass
    # Migrate the only setting stored by versions before 1.3.0.
    try:
        legacy_mode = palette_mode_path(state_dir).read_text(encoding="ascii").strip()
    except OSError:
        legacy_mode = "gradient"
    return settings_from_mapping({"palette_mode": legacy_mode})


def write_settings(state_dir: Path, settings: ShaderSettings) -> None:
    atomic_write(settings_path(state_dir), json.dumps(asdict(settings), indent=2) + "\n")
    atomic_write(palette_mode_path(state_dir), settings.palette_mode + "\n")


def read_last_colors(state_dir: Path) -> tuple[Rgb, ...]:
    try:
        values = json.loads(last_colors_path(state_dir).read_text(encoding="utf-8"))
        colors = tuple(tuple(component for component in color) for color in values)
        if all(len(color) == 3 and all(isinstance(component, int) and 0 <= component <= 255
                                       for component in color) for color in colors):
            return colors  # type: ignore[return-value]
    except (OSError, TypeError, ValueError):
        pass
    return ()


def write_last_colors(state_dir: Path, colors: tuple[Rgb, ...]) -> None:
    atomic_write(last_colors_path(state_dir), json.dumps(colors) + "\n")


def read_last_accent_colors(state_dir: Path) -> tuple[Rgb, ...]:
    original = last_colors_path(state_dir)
    accent = last_accent_colors_path(state_dir)
    try:
        if not accent.exists() and original.exists():
            colors = read_last_colors(state_dir)
            if colors:
                atomic_write(accent, json.dumps(colors) + "\n")
        values = json.loads(accent.read_text(encoding="utf-8"))
        colors = tuple(tuple(component for component in color) for color in values)
        if all(len(color) == 3 and all(isinstance(component, int) and 0 <= component <= 255
                                       for component in color) for color in colors):
            return colors  # type: ignore[return-value]
    except (OSError, TypeError, ValueError):
        pass
    return ()


def write_last_accent_colors(state_dir: Path, colors: tuple[Rgb, ...]) -> None:
    atomic_write(last_accent_colors_path(state_dir), json.dumps(colors) + "\n")


def apply_colors(state_dir: Path, shader: Path, colors: tuple[Rgb, ...]) -> None:
    settings = read_settings(state_dir)
    # Read before replacing last-colors.json so a pre-1.3.0 non-empty value can
    # seed the dedicated remembered-cover file during migration.
    remembered = read_last_accent_colors(state_dir)
    write_last_colors(state_dir, colors)
    if colors:
        write_last_accent_colors(state_dir, colors)
        remembered = colors
    effective = (
        remembered
        if not colors and settings.idle_mode == "last_cover"
        else colors
    )
    count = 1 if settings.palette_mode == "single" else settings.max_colors
    write_colors(state_dir, shader, effective[:count], settings)


def set_shader_settings(state_dir: Path, shader: Path, settings: ShaderSettings) -> None:
    write_settings(state_dir, settings)
    apply_colors(state_dir, shader, read_last_colors(state_dir))


def restore(state_dir: Path, shader: Path) -> None:
    backup = backup_path(state_dir)
    if not backup.exists() or not shader.exists():
        return
    try:
        current = shader.read_text(encoding="utf-8")
        original = backup.read_text(encoding="utf-8")
    except OSError:
        return
    if current.startswith(MARKER) and current != original:
        atomic_write(shader, original)


def cached_cover(state_dir: Path, uri: str) -> Optional[Path]:
    cache = state_dir / "covers"
    cache.mkdir(mode=0o700, parents=True, exist_ok=True)
    key = hashlib.sha256(uri.encode("utf-8")).hexdigest()
    target = cache / key
    if target.exists() and target.stat().st_size > 0:
        return target
    parsed = urlparse(uri)
    try:
        if parsed.scheme == "file":
            source = Path(unquote(parsed.path))
            if not source.is_file():
                return None
            # Cache copies prevent a player from replacing its cover mid-analysis.
            data = source.read_bytes()
        elif parsed.scheme in ("http", "https"):
            request = Request(uri, headers={"User-Agent": "Noctalia-Track-Accent/1.0"})
            with urlopen(request, timeout=8) as response:
                data = response.read(MAX_DOWNLOAD + 1)
            if len(data) > MAX_DOWNLOAD:
                return None
        else:
            return None
        with tempfile.NamedTemporaryFile("wb", dir=cache, delete=False) as output:
            output.write(data)
            temporary = Path(output.name)
        os.replace(temporary, target)
        return target
    except OSError:
        return None


def color_distance(first: Rgb, second: Rgb) -> float:
    return sum((left - right) ** 2 for left, right in zip(first, second)) ** 0.5


def extract_colors(image: Path) -> tuple[Rgb, ...]:
    """Return up to four populous, vivid and visually distinct cover colours."""
    imagemagick = shutil.which("magick") or shutil.which("convert")
    if imagemagick is None:
        return ()
    try:
        result = subprocess.run(
            [imagemagick, str(image), "-alpha", "on", "-resize", "96x96!", "-colors", "64",
             "-depth", "8", "-format", "%c", "histogram:info:-"],
            check=False, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=True, timeout=12,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ()
    candidates: list[tuple[float, Rgb]] = []
    for line in result.stdout.splitlines():
        match = HISTOGRAM.match(line)
        if not match:
            continue
        count, red, green, blue, alpha = match.groups()
        r, g, b, a = (int(float(value)) for value in (red, green, blue, alpha))
        if a < 40:
            continue
        maximum, minimum = max(r, g, b), min(r, g, b)
        value = maximum / 255.0
        saturation = 0.0 if maximum == 0 else (maximum - minimum) / maximum
        # Reject near-black, near-white and grey unless no usable hue exists.
        if (value < 0.14 or saturation < 0.30
                or (value > 0.91 and saturation < 0.55)):
            continue
        middle = 1.0 - abs(value - 0.58) / 0.58
        score = int(count) * (saturation ** 4) * (0.35 + max(0.0, middle)) * (a / 255.0)
        candidates.append((score, (r, g, b)))

    selected: list[Rgb] = []
    for _score, color in sorted(candidates, reverse=True):
        # Histogram quantization emits neighbouring shades of the same colour.
        # Keep only clearly separate accents so a red cover does not become a
        # barely perceptible red-to-red gradient.
        if all(color_distance(color, existing) >= 72.0 for existing in selected):
            selected.append(color)
            if len(selected) == 4:
                break

    # Hue order produces a stable, natural colour wheel around the border.
    return tuple(sorted(
        selected,
        key=lambda rgb: colorsys.rgb_to_hsv(*(component / 255.0 for component in rgb))[0],
    ))


def unwrap_dbus(value: object) -> object:
    """Remove busctl's JSON variant wrappers without assuming one exact shape."""
    if isinstance(value, list):
        return [unwrap_dbus(item) for item in value]
    if isinstance(value, dict):
        if set(value) == {"type", "data"}:
            return unwrap_dbus(value["data"])
        return {key: unwrap_dbus(item) for key, item in value.items()}
    return value


def find_active_player(value: object) -> Optional[dict]:
    if isinstance(value, dict):
        if "art_url" in value and "bus_name" in value:
            return value
        for child in value.values():
            found = find_active_player(child)
            if found is not None:
                return found
    elif isinstance(value, list):
        for child in value:
            found = find_active_player(child)
            if found is not None:
                return found
    return None


def active_art_uri() -> str:
    """Read exactly the player Noctalia selected for its media UI."""
    try:
        result = subprocess.run(
            ["busctl", "--user", "--json=short", "call", NOCTALIA_MPRIS_BUS,
             NOCTALIA_MPRIS_PATH, NOCTALIA_MPRIS_INTERFACE, "GetActivePlayer"],
            check=False, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            text=True, timeout=3,
        )
        if result.returncode != 0:
            return ""
        player = find_active_player(unwrap_dbus(json.loads(result.stdout)))
        return player.get("art_url", "") if isinstance(player, dict) else ""
    except (OSError, ValueError, subprocess.TimeoutExpired):
        return ""


def pid_path(state_dir: Path) -> Path:
    return state_dir / "watcher.pid"


def stop_watcher(state_dir: Path) -> None:
    try:
        pid = int(pid_path(state_dir).read_text(encoding="ascii"))
        if pid != os.getpid():
            os.kill(pid, signal.SIGTERM)
            deadline = time.monotonic() + 1.0
            while time.monotonic() < deadline:
                try:
                    os.kill(pid, 0)
                except ProcessLookupError:
                    break
                time.sleep(0.05)
    except (OSError, ValueError):
        pass
    try:
        pid_path(state_dir).unlink()
    except OSError:
        pass


def watch(state_dir: Path, shader: Path) -> None:
    state_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    lock_file = state_dir / "watcher.lock"
    with lock_file.open("w") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            return
        atomic_write(pid_path(state_dir), str(os.getpid()) + "\n")
        stopped = False

        def stop(_signum: int, _frame: object) -> None:
            nonlocal stopped
            stopped = True

        signal.signal(signal.SIGTERM, stop)
        signal.signal(signal.SIGINT, stop)
        # dbus-monitor owns a durable session-bus match. Unlike `busctl monitor`,
        # it does not terminate after a short service-owner transition.
        command = [
            "dbus-monitor", "--session",
            "type='signal',sender='dev.noctalia.Mpris',interface='dev.noctalia.Mpris'",
        ]
        analysis_cache: dict[str, tuple[Rgb, ...]] = {}

        def analyse(uri: str) -> tuple[Rgb, ...]:
            if uri in analysis_cache:
                return analysis_cache[uri]
            image = cached_cover(state_dir, uri)
            colors = extract_colors(image) if image else ()
            analysis_cache[uri] = colors
            return colors

        with ThreadPoolExecutor(max_workers=2, thread_name_prefix="cover-accent") as workers:
            restart_attempts = 0
            while not stopped and restart_attempts < 3:
                try:
                    process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                                               text=True, bufsize=1)
                except OSError:
                    apply_colors(state_dir, shader, ())
                    return
                assert process.stdout is not None
                generation = 0
                pending: dict[Future[tuple[Rgb, ...]], int] = {}
                seen_event = False

                def schedule_current_cover() -> None:
                    nonlocal generation
                    generation += 1
                    art_uri = active_art_uri()
                    if not art_uri:
                        apply_colors(state_dir, shader, ())
                        return
                    pending[workers.submit(analyse, art_uri)] = generation

                schedule_current_cover()
                while not stopped and process.poll() is None:
                    # select keeps this loop responsive to completed image work even if
                    # MPRIS emits nothing. A newer metadata line invalidates older jobs.
                    readable, _, _ = select.select([process.stdout], [], [], 0.08)
                    if readable:
                        raw = process.stdout.readline()
                        if ("member=ActivePlayerChanged" in raw
                                or "member=TrackChanged" in raw
                                or "member=PlayersChanged" in raw):
                            seen_event = True
                            schedule_current_cover()
                    for future, job_generation in list(pending.items()):
                        if not future.done():
                            continue
                        del pending[future]
                        try:
                            colors = future.result()
                        except Exception:
                            colors = ()
                        if job_generation == generation:
                            apply_colors(state_dir, shader, colors)
                process.terminate()
                try:
                    process.wait(timeout=1)
                except subprocess.TimeoutExpired:
                    process.kill()
                if not stopped:
                    # A short bounded recovery covers a D-Bus reconnect, without polling.
                    restart_attempts = 0 if seen_event else restart_attempts + 1
                    time.sleep(restart_attempts)
        try:
            pid_path(state_dir).unlink()
        except OSError:
            pass


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--watch", action="store_true")
    group.add_argument("--restore", action="store_true")
    group.add_argument("--set-settings", "--set-mode", dest="set_settings", action="store_true")
    parser.add_argument("--state-dir", required=True)
    parser.add_argument("--shader", required=True)
    parser.add_argument("--mode", choices=sorted(PALETTE_MODES), default="gradient")
    parser.add_argument("--idle-mode", choices=sorted(IDLE_MODES), default="native")
    parser.add_argument("--silence-brightness", type=float, default=0.4)
    parser.add_argument("--dark-color-floor", type=float, default=0.5)
    parser.add_argument("--spectrum-gain", type=float, default=1.8)
    parser.add_argument("--bass-gain", type=float, default=0.35)
    parser.add_argument("--max-colors", type=int, default=4)
    parser.add_argument("--gradient-speed", type=float, default=0.0)
    parser.add_argument("--fallback-color", default="#7C6FDC")
    args = parser.parse_args()
    state_dir, shader = expand(args.state_dir), expand(args.shader)
    settings = settings_from_mapping({
        "palette_mode": args.mode,
        "idle_mode": args.idle_mode,
        "silence_brightness": args.silence_brightness,
        "dark_color_floor": args.dark_color_floor,
        "spectrum_gain": args.spectrum_gain,
        "bass_gain": args.bass_gain,
        "max_colors": args.max_colors,
        "gradient_speed": args.gradient_speed,
        "fallback_color": args.fallback_color,
    })
    if args.restore:
        stop_watcher(state_dir)
        restore(state_dir, shader)
    elif args.set_settings:
        set_shader_settings(state_dir, shader, settings)
    else:
        write_settings(state_dir, settings)
        watch(state_dir, shader)
    return 0


